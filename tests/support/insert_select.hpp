#pragma once
#include <catch2/catch_test_macros.hpp>
#include <stdexcept>

#include "asterorm/repository.hpp"
#include "asterorm/sql/typed.hpp"

struct insert_source_row {
    int source_id{};
    int price{};
    std::optional<std::string> note;
    bool active{};
};
template <> struct asterorm::entity_traits<insert_source_row> {
    static constexpr const char* table = "insert_select_source";
    static constexpr auto columns =
        std::make_tuple(asterorm::column<&insert_source_row::source_id>("source_id"),
                        asterorm::column<&insert_source_row::price>("price"),
                        asterorm::column<&insert_source_row::note>("note"),
                        asterorm::column<&insert_source_row::active>("active"));
};
struct insert_archive_row {
    std::optional<std::int64_t> archive_id;
    int source_id{};
    int price{};
    std::optional<std::string> note;
    int created{};
    int doubled{};
};
template <> struct asterorm::entity_traits<insert_archive_row> {
    static constexpr const char* table = "insert_select_archive";
    static constexpr auto primary_key = asterorm::pk<&insert_archive_row::archive_id>("archive_id");
    static constexpr auto columns = std::make_tuple(
        asterorm::column<&insert_archive_row::archive_id>("archive_id",
                                                          asterorm::generated::by_default),
        asterorm::column<&insert_archive_row::source_id>("source_id"),
        asterorm::column<&insert_archive_row::price>("price"),
        asterorm::column<&insert_archive_row::note>("note"),
        asterorm::column<&insert_archive_row::created>("created", asterorm::generated::by_default),
        asterorm::column<&insert_archive_row::doubled>("doubled", asterorm::generated::always));
};

namespace asterorm::test {
template <typename Session> void check_insert_select(Session& db) {
    namespace sql = asterorm::sql;
    constexpr auto dialect = sql::dialect_for_session<Session>();
    const std::string id_definition =
        dialect == sql::dialect::postgres ? "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        : dialect == sql::dialect::mysql  ? "BIGINT AUTO_INCREMENT PRIMARY KEY"
                                          : "INTEGER PRIMARY KEY AUTOINCREMENT";
    auto created = db.with_connection([&](auto& connection) -> result<void> {
        auto source = connection.execute(
            "CREATE TEMPORARY TABLE insert_select_source (source_id INTEGER PRIMARY KEY, price "
            "INTEGER NOT NULL, note VARCHAR(255), active BOOLEAN NOT NULL)");
        if (!source) {
            return std::unexpected(source.error());
        }
        auto target = connection.execute(
            "CREATE TEMPORARY TABLE insert_select_archive (archive_id " + id_definition +
            ", source_id INTEGER NOT NULL UNIQUE, price INTEGER NOT NULL, note VARCHAR(255), "
            "created INTEGER DEFAULT 77, doubled INTEGER GENERATED ALWAYS AS (price * 2) STORED)");
        if (!target) {
            return std::unexpected(target.error());
        }
        auto seed =
            connection.execute_params("INSERT INTO insert_select_source VALUES "
                                      "(1,10,$1,TRUE),(2,20,NULL,TRUE),(3,30,'third',FALSE)",
                                      {"quote' ; --"});
        if (!seed) {
            return std::unexpected(seed.error());
        }
        return {};
    });
    REQUIRE(created.has_value());
    asterorm::repository repo{db};
    auto paged = [] {
        auto source = sql::select({"s.source_id", "s.price", "s.note"})
                          .from("insert_select_source")
                          .where(sql::col("s.active") == sql::val(true))
                          .order_by("s.source_id")
                          .limit(1)
                          .offset(1)
                          .build();
        source.table_alias = "s";
        source.columns.clear();
        source.items = {
            {
                .column_name = "s.source_id",
                .fn = nullptr,
                .alias = "copied_id",
            },
            {
                .column_name = "s.price",
                .fn = nullptr,
                .alias = std::nullopt,
            },
            {
                .column_name = "s.note",
                .fn = nullptr,
                .alias = std::nullopt,
            },
        };
        return source;
    };
    auto active_source = [] {
        namespace typed = sql::typed;
        return typed::select_cols(typed::col<&insert_source_row::source_id>,
                                  typed::col<&insert_source_row::price>,
                                  typed::col<&insert_source_row::note>)
            .where(typed::col<&insert_source_row::active> == typed::val(true))
            .order_by(typed::col<&insert_source_row::source_id>)
            .build();
    };
    int events = 0;
    int errors = 0;
    db.set_observer([&](const query_event& event) {
        ++events;
        if (event.error) {
            ++errors;
        }
    });
    auto transaction = db.begin();
    REQUIRE(transaction.has_value());
    REQUIRE(repo.template insert_select<insert_archive_row>(paged()) == 1);
    REQUIRE(events == 1);
    auto copied = db.with_connection([](auto& connection) {
        return connection.execute(
            "SELECT archive_id,source_id,price,note,created,doubled FROM insert_select_archive");
    });
    REQUIRE(copied.has_value());
    REQUIRE(copied->rows() == 1);
    REQUIRE(copied->get_int64(0, 0).value() > 0);
    REQUIRE(copied->get_int64(0, 1) == 2);
    REQUIRE(copied->get_int64(0, 2) == 20);
    REQUIRE(copied->is_null(0, 3));
    REQUIRE(copied->get_int64(0, 4) == 77);
    REQUIRE(copied->get_int64(0, 5) == 40);
    REQUIRE(repo.template insert_select<insert_archive_row>(
                sql::select({"source_id", "price", "note"})
                    .from("insert_select_source")
                    .where(sql::col("source_id") == sql::val(999))
                    .build()) == 0);
    REQUIRE_FALSE(repo.template insert_select<insert_archive_row>(
                          sql::select({"source_id"}).from("insert_select_source").build())
                      .has_value());
    REQUIRE(events == 2);
    auto duplicate = repo.template insert_select<insert_archive_row>(paged());
    REQUIRE_FALSE(duplicate.has_value());
    REQUIRE(duplicate.error().kind == db_error_kind::constraint_violation);
    REQUIRE(events == 3);
    REQUIRE(errors == 1);
    REQUIRE(transaction->rollback().has_value());
    auto empty = db.with_connection([](auto& connection) {
        return connection.execute("SELECT COUNT(*) FROM insert_select_archive");
    });
    REQUIRE(empty.has_value());
    REQUIRE(empty->get_int64(0, 0) == 0);
    auto committed = db.begin();
    REQUIRE(committed.has_value());
    REQUIRE(repo.template insert_select<insert_archive_row>(active_source()) == 2);
    REQUIRE(committed->commit().has_value());
    REQUIRE(events == 4);
    auto stored = db.with_connection([](auto& connection) {
        return connection.execute(
            "SELECT note,created,doubled FROM insert_select_archive ORDER BY source_id");
    });
    REQUIRE(stored.has_value());
    REQUIRE(stored->rows() == 2);
    REQUIRE(stored->get_string(0, 0) == "quote' ; --");
    REQUIRE(stored->get_int64(0, 1) == 77);
    REQUIRE(stored->get_int64(0, 2) == 20);
    REQUIRE(stored->is_null(1, 0));
    if constexpr (dialect == sql::dialect::mysql) {
        auto self =
            sql::select({"source_id", "price", "note"}).from("insert_select_archive").build();
        REQUIRE_FALSE(repo.template insert_select<insert_archive_row>(std::move(self)).has_value());
        REQUIRE(events == 4);
    }
    int throwing_events = 0;
    db.set_observer([&](const query_event&) {
        ++throwing_events;
        throw std::runtime_error("insert observer identity");
    });
    try {
        (void)repo.template insert_select<insert_archive_row>(
            sql::select({"source_id", "price", "note"})
                .from("insert_select_source")
                .where(sql::col("source_id") == sql::val(3))
                .build());
        FAIL("Observer exception must propagate");
    } catch (const std::runtime_error& failure) {
        REQUIRE(std::string{failure.what()} == "insert observer identity");
    }
    REQUIRE(throwing_events == 1);
    db.set_observer({});
    auto persisted = db.with_connection([](auto& connection) {
        return connection.execute("SELECT COUNT(*) FROM insert_select_archive");
    });
    REQUIRE(persisted.has_value());
    REQUIRE(persisted->get_int64(0, 0) == 3);
}
} // namespace asterorm::test
